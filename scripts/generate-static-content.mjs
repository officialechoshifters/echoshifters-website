// Generates netlify/functions/_shared/static-content.mjs from public/carousels.
// Run: node scripts/generate-static-content.mjs
//
// The generated module embeds the members-only text content (carousel index,
// per-article captions and slide text) so the gated /content/* function can
// serve it from the lambda bundle. Images stay on /carousels/... as plain
// static files — they're useless without the text, so they stay public.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const root = process.cwd()
const carouselsDir = join(root, 'public', 'carousels')
const outFile = join(root, 'netlify', 'functions', '_shared', 'static-content.mjs')

if (!existsSync(carouselsDir)) {
  console.error(`No ${carouselsDir} — run this from my-clerk-vite-app/`)
  process.exit(1)
}

const index = JSON.parse(readFileSync(join(carouselsDir, 'index.json'), 'utf8'))

// Embed every article's caption and slides as a flat map keyed by article id.
const articles = {}
const dirs = readdirSync(carouselsDir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)

for (const dir of dirs) {
  const id = dir.replace(/^article_/, '')
  const base = join(carouselsDir, dir)
  const entry = {}
  const captionPath = join(base, 'caption.txt')
  if (existsSync(captionPath)) entry.caption = readFileSync(captionPath, 'utf8')
  const slidesPath = join(base, 'slides.json')
  if (existsSync(slidesPath)) {
    try { entry.slides = JSON.parse(readFileSync(slidesPath, 'utf8')) } catch { /* skip malformed */ }
  }
  if (entry.caption || entry.slides) articles[id] = entry
}

const module = `// AUTO-GENERATED by scripts/generate-static-content.mjs — do not edit by hand.
// Members-only text content for the gated /content/* function. Images stay
// public on /carousels/...; this is the text that's worth protecting.
export const CAROUSELS_INDEX = ${JSON.stringify(index)}

export const ARTICLES = ${JSON.stringify(articles)}

export const GENERATED_AT = ${JSON.stringify(new Date().toISOString())}
`

writeFileSync(outFile, module)

const articleCount = Object.keys(articles).length
const carouselCount = Array.isArray(index.carousels) ? index.carousels.length : 0
const kb = Math.round(Buffer.byteLength(module, 'utf8') / 1024)
console.log(`static-content.mjs generated: ${carouselCount} carousels in index, ${articleCount} article text bundles, ${kb}KB total`)
